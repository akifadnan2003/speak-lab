#!/usr/bin/env node
/**
 * Generates the curriculum the browser bundle ships: the full content with the answer keys of
 * every assessment lesson removed (see src/features/curriculum/content/redact.ts). Real builds
 * import only this generated module, so assessment keys never reach the client; the full
 * content exists in preview builds (no backend) and in the Edge Function's generated copy.
 *
 *   node scripts/build-client-content.mjs           # write
 *   node scripts/build-client-content.mjs --check   # exit 1 when the generated module is stale
 */
import { existsSync, mkdirSync, readFileSync, rmSync, writeFileSync } from 'node:fs'
import path from 'node:path'
import { fileURLToPath, pathToFileURL } from 'node:url'
import { build } from 'vite'

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')
const OUT = path.join(root, 'src', 'features', 'curriculum', 'content', 'generated', 'client-curriculum.ts')
const TMP = path.join(root, 'node_modules', '.cache', 'speaklab-client-content')
const HEADER = `// GENERATED by scripts/build-client-content.mjs — do not edit.
// The curriculum with assessment answer keys removed; this is what real builds ship.
// Run \`npm run sync:content\` after changing content under src/features/curriculum/content.
/* oxlint-disable */
`

rmSync(TMP, { recursive: true, force: true })
await build({
  configFile: false,
  root,
  logLevel: 'silent',
  resolve: { alias: { '@': path.join(root, 'src') } },
  build: {
    ssr: path.join(root, 'scripts', 'client-content.entry.ts'),
    outDir: TMP,
    emptyOutDir: true,
    minify: false,
    rollupOptions: { output: { format: 'es', entryFileNames: 'entry.mjs' } },
  },
})

const mod = await import(pathToFileURL(path.join(TMP, 'entry.mjs')).href)
const redacted = mod.redactAssessmentKeys(mod.CURRICULUM)
const json = JSON.stringify(redacted)
const text = `${HEADER}export const CLIENT_CURRICULUM_JSON = ${JSON.stringify(json)}\n`

if (process.argv.includes('--check')) {
  if (!existsSync(OUT) || readFileSync(OUT, 'utf8') !== text) {
    console.error('src/features/curriculum/content/generated/client-curriculum.ts is out of date. Run `npm run sync:content`.')
    process.exit(1)
  }
  console.log(`client curriculum is in sync (${redacted.length} chapters, ${(json.length / 1024).toFixed(0)} KB)`)
} else {
  mkdirSync(path.dirname(OUT), { recursive: true })
  writeFileSync(OUT, text)
  console.log(`wrote ${path.relative(root, OUT)} (${redacted.length} chapters, ${(json.length / 1024).toFixed(0)} KB)`)
}
