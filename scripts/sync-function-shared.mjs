#!/usr/bin/env node
/**
 * Copies the pure curriculum modules (schemas, content, grading engine, progression and
 * assessment rules) into `supabase/functions/_shared/` so the `assessment` Edge Function grades
 * with exactly the code and content the app ships, without the browser build depending on Deno.
 *
 * The copy is generated, committed and verified in CI (`--check`): the source of truth stays in
 * `src/`. Import specifiers are rewritten for Deno (explicit `.ts` extensions, `npm:zod@<ver>`).
 *
 *   node scripts/sync-function-shared.mjs           # write
 *   node scripts/sync-function-shared.mjs --check   # exit 1 when the copy is stale
 */
import { existsSync, mkdirSync, readdirSync, readFileSync, rmSync, statSync, writeFileSync } from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')
const SRC = path.join(root, 'src', 'features')
const OUT = path.join(root, 'supabase', 'functions', '_shared', 'features')
const SOURCES = [
  'curriculum/schema',
  'curriculum/content/authoring.ts',
  'curriculum/content/curriculum-map.ts',
  'curriculum/content/chapters',
  'curriculum/ports.ts',
  'curriculum/progression.ts',
  'curriculum/assessment-rules.ts',
  'exercises/engine/grade.ts',
  'exercises/engine/normalize.ts',
]
const pkg = JSON.parse(readFileSync(path.join(root, 'package.json'), 'utf8'))
const ZOD = `npm:zod@${pkg.dependencies.zod.replace(/^[\^~]/, '')}`
const HEADER = `// GENERATED by scripts/sync-function-shared.mjs from src/features — do not edit.\n// Run \`npm run sync:functions\` after changing the source module.\n`

function listFiles(rel) {
  const abs = path.join(SRC, rel)
  if (statSync(abs).isFile()) return [rel]
  const out = []
  for (const entry of readdirSync(abs, { withFileTypes: true })) {
    const child = path.posix.join(rel, entry.name)
    if (entry.isDirectory()) out.push(...listFiles(child))
    else if (entry.name.endsWith('.ts') && !/\.test\.tsx?$/.test(entry.name)) out.push(child)
  }
  return out
}

/** Resolve a specifier to a `src/features`-relative module path with an explicit extension. */
function resolveModule(fromRel, spec) {
  let target
  if (spec.startsWith('@/features/')) target = spec.slice('@/features/'.length)
  else if (spec.startsWith('.')) target = path.posix.normalize(path.posix.join(path.posix.dirname(fromRel), spec))
  else return null
  if (existsSync(path.join(SRC, `${target}.ts`))) return `${target}.ts`
  if (existsSync(path.join(SRC, target, 'index.ts'))) return `${target}/index.ts`
  throw new Error(`${fromRel}: cannot resolve import '${spec}'`)
}

function rewrite(rel, source) {
  return source.replace(/(from\s+|import\s+)(['"])([^'"]+)\2/g, (whole, lead, quote, spec) => {
    if (spec === 'zod') return `${lead}${quote}${ZOD}${quote}`
    const target = resolveModule(rel, spec)
    if (!target) throw new Error(`${rel}: import '${spec}' is not allowed in shared function code`)
    let relative = path.posix.relative(path.posix.dirname(rel), target)
    if (!relative.startsWith('.')) relative = `./${relative}`
    return `${lead}${quote}${relative}${quote}`
  })
}

const generated = new Map()
for (const source of SOURCES) {
  for (const rel of listFiles(source)) {
    const text = readFileSync(path.join(SRC, rel), 'utf8')
    generated.set(rel, HEADER + rewrite(rel, text))
  }
}

const check = process.argv.includes('--check')
if (check) {
  const problems = []
  for (const [rel, text] of generated) {
    const file = path.join(OUT, rel)
    if (!existsSync(file)) problems.push(`missing ${rel}`)
    else if (readFileSync(file, 'utf8') !== text) problems.push(`stale ${rel}`)
  }
  const walk = (dir, base = '') => {
    if (!existsSync(dir)) return
    for (const entry of readdirSync(dir, { withFileTypes: true })) {
      const rel = path.posix.join(base, entry.name)
      if (entry.isDirectory()) walk(path.join(dir, entry.name), rel)
      else if (!generated.has(rel)) problems.push(`unexpected ${rel}`)
    }
  }
  walk(OUT)
  if (problems.length) {
    console.error('supabase/functions/_shared is out of date. Run `npm run sync:functions`.\n' + problems.map((p) => `  - ${p}`).join('\n'))
    process.exit(1)
  }
  console.log(`shared function code is in sync (${generated.size} files)`)
} else {
  rmSync(OUT, { recursive: true, force: true })
  for (const [rel, text] of generated) {
    const file = path.join(OUT, rel)
    mkdirSync(path.dirname(file), { recursive: true })
    writeFileSync(file, text)
  }
  console.log(`wrote ${generated.size} files to supabase/functions/_shared/features`)
}
