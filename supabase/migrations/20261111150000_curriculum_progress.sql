-- SpeakLab · M3 · Curriculum progress, exercise attempts, tutor overrides and server-graded
-- assessments.
--
-- Additive only. Nothing in the M2 identity tables is altered except the list of allowed
-- account_events types (extended, never narrowed).
--
-- Trust model
--   * lesson_progress and exercise_attempts are the learner's own practice record. Students write
--     their own rows directly (RLS: student_id = auth.uid()). They can only ever claim progress on
--     practice lessons: the app ignores lesson_progress rows for assessment lessons.
--   * assessment_attempts is the authoritative mastery record. It is written exclusively by the
--     `assessment` Edge Function with the service role, which grades the raw answers itself.
--     Clients have SELECT only. Chapter completion depends on a passed assessment attempt, so a
--     student cannot promote themselves through a chapter by inserting rows.
--   * chapter_access_overrides (unlock / skip) are written by the tutor for linked students only.
--   * The tutor reads every table for linked students; nobody reads another student's rows.

-- ---------------------------------------------------------------------------------------------
-- Types
-- ---------------------------------------------------------------------------------------------
create type public.lesson_progress_status as enum ('in_progress', 'completed', 'skipped');
create type public.chapter_override_kind as enum ('unlock', 'skip');
create type public.assessment_attempt_status as enum ('in_progress', 'submitted', 'voided');

-- ---------------------------------------------------------------------------------------------
-- Helpers
-- ---------------------------------------------------------------------------------------------
-- True when the caller is the active tutor and p_student_id is one of their linked students.
create or replace function public.tutor_of(p_student_id uuid)
returns boolean
language sql
stable
security definer
set search_path = ''
as $$
  select public.is_tutor()
    and exists (
      select 1 from public.tutor_students ts
      where ts.tutor_id = (select auth.uid()) and ts.student_id = p_student_id
    );
$$;
revoke all on function public.tutor_of(uuid) from public, anon;
grant execute on function public.tutor_of(uuid) to authenticated, service_role;

-- ---------------------------------------------------------------------------------------------
-- lesson_progress: one row per (student, chapter, lesson). Practice record, client-written.
-- ---------------------------------------------------------------------------------------------
create table public.lesson_progress (
  student_id uuid not null references public.profiles (id) on delete cascade,
  chapter_id text not null,
  lesson_id text not null,
  status public.lesson_progress_status not null,
  best_score smallint,
  last_score smallint,
  completed_at timestamptz,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  primary key (student_id, chapter_id, lesson_id),
  constraint lesson_progress_chapter_id check (chapter_id ~ '^[a-z0-9]+(-[a-z0-9]+)*$'),
  constraint lesson_progress_lesson_id check (lesson_id ~ '^[a-z0-9]+(-[a-z0-9]+)*$'),
  constraint lesson_progress_best_score check (best_score is null or best_score between 0 and 100),
  constraint lesson_progress_last_score check (last_score is null or last_score between 0 and 100),
  constraint lesson_progress_completed_at check (status <> 'completed' or completed_at is not null)
);
create index lesson_progress_student_idx on public.lesson_progress (student_id, updated_at desc);
create trigger lesson_progress_set_updated_at before update on public.lesson_progress
  for each row execute function public.set_updated_at();

-- ---------------------------------------------------------------------------------------------
-- exercise_attempts: every checked answer in a practice lesson. The id is generated by the
-- client and doubles as the idempotency key (a retried write is a no-op).
-- ---------------------------------------------------------------------------------------------
create table public.exercise_attempts (
  id uuid primary key,
  student_id uuid not null references public.profiles (id) on delete cascade,
  chapter_id text not null,
  chapter_version integer not null,
  lesson_id text not null,
  exercise_id text not null,
  exercise_type text not null,
  attempt_number smallint not null,
  answer jsonb not null,
  correct boolean not null,
  score numeric(4, 3) not null,
  hint_used boolean not null default false,
  created_at timestamptz not null default now(),
  constraint exercise_attempts_chapter_id check (chapter_id ~ '^[a-z0-9]+(-[a-z0-9]+)*$'),
  constraint exercise_attempts_lesson_id check (lesson_id ~ '^[a-z0-9]+(-[a-z0-9]+)*$'),
  constraint exercise_attempts_exercise_id check (exercise_id ~ '^[a-z0-9]+(-[a-z0-9]+)*$'),
  constraint exercise_attempts_chapter_version check (chapter_version >= 1),
  constraint exercise_attempts_type check (
    exercise_type in (
      'multiple_choice', 'fill_blank', 'sentence_ordering', 'error_correction', 'matching',
      'question_formation', 'sentence_transformation', 'speaking_prompt', 'guided_writing'
    )
  ),
  constraint exercise_attempts_number check (attempt_number between 1 and 10),
  constraint exercise_attempts_answer_object check (jsonb_typeof(answer) = 'object'),
  constraint exercise_attempts_score check (score between 0 and 1)
);
create index exercise_attempts_student_lesson_idx
  on public.exercise_attempts (student_id, lesson_id, created_at desc);

-- ---------------------------------------------------------------------------------------------
-- chapter_access_overrides: tutor decisions that unlock a chapter early or skip it entirely
-- (placement). One row per (student, chapter); removing the row removes the override.
-- ---------------------------------------------------------------------------------------------
create table public.chapter_access_overrides (
  student_id uuid not null references public.profiles (id) on delete cascade,
  chapter_id text not null,
  kind public.chapter_override_kind not null,
  created_by uuid not null references public.profiles (id) on delete cascade,
  created_at timestamptz not null default now(),
  primary key (student_id, chapter_id),
  constraint chapter_access_overrides_chapter_id check (chapter_id ~ '^[a-z0-9]+(-[a-z0-9]+)*$')
);

-- ---------------------------------------------------------------------------------------------
-- assessment_attempts: server-graded chapter checks. Service role only.
-- ---------------------------------------------------------------------------------------------
create table public.assessment_attempts (
  id uuid primary key default gen_random_uuid(),
  student_id uuid not null references public.profiles (id) on delete cascade,
  chapter_id text not null,
  chapter_version integer not null,
  lesson_id text not null,
  attempt_number smallint not null,
  status public.assessment_attempt_status not null default 'in_progress',
  pass_mark smallint not null,
  -- Raw answers as submitted, keyed by exercise id (array of { exerciseId, answer }).
  answers jsonb not null default '[]'::jsonb,
  -- Per-exercise grading (array of { exerciseId, correct, score }); never contains the answer key.
  results jsonb not null default '[]'::jsonb,
  score smallint,
  passed boolean,
  started_at timestamptz not null default now(),
  expires_at timestamptz not null,
  submitted_at timestamptz,
  voided_at timestamptz,
  constraint assessment_attempts_chapter_id check (chapter_id ~ '^[a-z0-9]+(-[a-z0-9]+)*$'),
  constraint assessment_attempts_lesson_id check (lesson_id ~ '^[a-z0-9]+(-[a-z0-9]+)*$'),
  constraint assessment_attempts_chapter_version check (chapter_version >= 1),
  constraint assessment_attempts_number check (attempt_number >= 1),
  constraint assessment_attempts_pass_mark check (pass_mark between 0 and 100),
  constraint assessment_attempts_answers_array check (jsonb_typeof(answers) = 'array'),
  constraint assessment_attempts_results_array check (jsonb_typeof(results) = 'array'),
  constraint assessment_attempts_score check (score is null or score between 0 and 100),
  constraint assessment_attempts_submitted check (
    status <> 'submitted' or (submitted_at is not null and score is not null and passed is not null)
  )
);
-- At most one open attempt per student and assessment.
create unique index assessment_attempts_open_idx
  on public.assessment_attempts (student_id, chapter_id, lesson_id) where status = 'in_progress';
create index assessment_attempts_student_idx
  on public.assessment_attempts (student_id, chapter_id, lesson_id, started_at desc);

-- ---------------------------------------------------------------------------------------------
-- Audit: new account_events types (additive) and a trigger for tutor overrides.
-- ---------------------------------------------------------------------------------------------
alter table public.account_events drop constraint account_events_type;
alter table public.account_events add constraint account_events_type check (
  event_type in (
    'owner_bootstrapped',
    'invitation_sent',
    'invitation_resent',
    'invitation_revoked',
    'invitation_accepted',
    'account_created',
    'account_disabled',
    'account_reactivated',
    'onboarding_completed',
    'chapter_override_set',
    'chapter_override_cleared',
    'assessment_submitted',
    'assessment_reset'
  )
);

create or replace function public.log_chapter_override()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
begin
  if tg_op = 'INSERT' then
    insert into public.account_events (user_id, actor_id, event_type, metadata)
    values (
      new.student_id,
      new.created_by,
      'chapter_override_set',
      jsonb_build_object('chapter_id', new.chapter_id, 'kind', new.kind)
    );
    return new;
  end if;
  insert into public.account_events (user_id, actor_id, event_type, metadata)
  values (
    old.student_id,
    auth.uid(),
    'chapter_override_cleared',
    jsonb_build_object('chapter_id', old.chapter_id, 'kind', old.kind)
  );
  return old;
end;
$$;
create trigger chapter_access_overrides_audit
  after insert or delete on public.chapter_access_overrides
  for each row execute function public.log_chapter_override();

-- ---------------------------------------------------------------------------------------------
-- Grants (explicit)
-- ---------------------------------------------------------------------------------------------
revoke all on public.lesson_progress, public.exercise_attempts, public.chapter_access_overrides,
  public.assessment_attempts from anon, authenticated;

grant select, insert, update on public.lesson_progress to authenticated;
grant select, insert on public.exercise_attempts to authenticated;
grant select, insert, delete on public.chapter_access_overrides to authenticated;
grant select on public.assessment_attempts to authenticated;

grant all on public.lesson_progress, public.exercise_attempts, public.chapter_access_overrides,
  public.assessment_attempts to service_role;

-- ---------------------------------------------------------------------------------------------
-- Row Level Security
-- ---------------------------------------------------------------------------------------------
alter table public.lesson_progress enable row level security;
alter table public.exercise_attempts enable row level security;
alter table public.chapter_access_overrides enable row level security;
alter table public.assessment_attempts enable row level security;

-- lesson_progress
create policy "lesson_progress: own rows or linked tutor read" on public.lesson_progress
  for select to authenticated
  using (student_id = (select auth.uid()) or public.tutor_of(student_id));

create policy "lesson_progress: active student inserts own" on public.lesson_progress
  for insert to authenticated
  with check (student_id = (select auth.uid()) and public.is_active());

create policy "lesson_progress: active student updates own" on public.lesson_progress
  for update to authenticated
  using (student_id = (select auth.uid()) and public.is_active())
  with check (student_id = (select auth.uid()) and public.is_active());

-- exercise_attempts
create policy "exercise_attempts: own rows or linked tutor read" on public.exercise_attempts
  for select to authenticated
  using (student_id = (select auth.uid()) or public.tutor_of(student_id));

create policy "exercise_attempts: active student inserts own" on public.exercise_attempts
  for insert to authenticated
  with check (student_id = (select auth.uid()) and public.is_active());

-- chapter_access_overrides
create policy "chapter_access_overrides: own rows or linked tutor read" on public.chapter_access_overrides
  for select to authenticated
  using (student_id = (select auth.uid()) or public.tutor_of(student_id));

create policy "chapter_access_overrides: tutor sets for linked students" on public.chapter_access_overrides
  for insert to authenticated
  with check (public.tutor_of(student_id) and created_by = (select auth.uid()) and public.is_active());

create policy "chapter_access_overrides: tutor clears for linked students" on public.chapter_access_overrides
  for delete to authenticated
  using (public.tutor_of(student_id) and public.is_active());

-- assessment_attempts (read-only for clients; the Edge Function writes with the service role)
create policy "assessment_attempts: own rows or linked tutor read" on public.assessment_attempts
  for select to authenticated
  using (student_id = (select auth.uid()) or public.tutor_of(student_id));
